def normalize_language_code(value: str) -> Optional[str]:
    """Normalize a string (code, display name, 3-letter ISO code) to a canonical code.

    Returns the uppercase canonical code (e.g., 'EN', 'KO', 'RU') if recognized, or None.
    """
    if not value:
        return None
    val_clean = value.strip()
    if not val_clean:
        return None

    val_lower = val_clean.lower()
    if val_lower in LANGUAGE_ALIAS_MAP:
        return LANGUAGE_ALIAS_MAP[val_lower]

    val_upper = val_clean.upper()
    if val_upper in CANONICAL_CODES:
        return val_upper

    return None


def get_display_name(code: str) -> str:
    """Get the exact canonical display name for a code."""
    if not code:
        return ""
    code_upper = code.strip().upper()
    return CANONICAL_LANGUAGE_MAP.get(code_upper, code_upper)


def is_canonical_code(code: str) -> bool:
    """Check if a code is a canonical 2-letter ISO 639-1 language code."""
    if not code:
        return False
    return code.strip().upper() in CANONICAL_CODES
